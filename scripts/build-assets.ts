/**
 * Regenerates `src/app/ui/assets.ts` from the card art under `public/images/`.
 *
 * Crumb loads one embedded document with `img-src data:` and no server, so the
 * card images travel with the bundle as data URIs rather than as fetched files.
 * Run `bun run assets` after changing any PNG under `public/images/`.
 */
import { readdir } from "node:fs/promises";

const SOURCE_DIR = new URL("../public/images/", import.meta.url);
const OUTPUT = new URL("../src/app/ui/assets.ts", import.meta.url);

const CARD_FRONTS = ["front1", "front2", "front3", "front4", "front5", "front6", "front7", "front8"] as const;
const CARD_BACK = "back";

async function encode(name: string): Promise<string> {
  const file = Bun.file(new URL(`${name}.png`, SOURCE_DIR));
  if (!(await file.exists())) throw new Error(`Missing image: public/images/${name}.png`);
  const base64 = Buffer.from(await file.arrayBuffer()).toString("base64");
  return `data:image/png;base64,${base64}`;
}

const present = new Set((await readdir(SOURCE_DIR)).map((entry) => entry.replace(/\.png$/, "")));
for (const required of [...CARD_FRONTS, CARD_BACK]) {
  if (!present.has(required)) throw new Error(`public/images/${required}.png is required but absent`);
}

const fronts = await Promise.all(CARD_FRONTS.map(encode));
const back = await encode(CARD_BACK);

const body = `// Generated by scripts/build-assets.ts — do not edit by hand.
// Run \`bun run assets\` to regenerate from public/images/*.png.

export const cardImages: readonly string[] = [
${fronts.map((uri) => `  ${JSON.stringify(uri)},`).join("\n")}
];

export const backImage: string = ${JSON.stringify(back)};
`;

await Bun.write(OUTPUT, body);
console.log(`Wrote ${CARD_FRONTS.length} front images and 1 back image to src/app/ui/assets.ts`);
